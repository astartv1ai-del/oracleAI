def language_and_gender_guidance(user) -> str:
    """Возвращает обязательное правило языка и грамматического рода для агента."""
    lang = user["lang"] or "ru"
    gender = user["gender"]
    if lang == "en":
        return (
            "Language and address (mandatory):\n"
            "- Reply in English unless the user explicitly asks for another language.\n"
            "- Use gender-neutral wording. Address the user as ‘you/your’; use singular ‘they/them’ "
            "only when third-person wording is unavoidable. Do not infer gender."
        )
    if gender == "f":
        return (
            "Язык и обращение (обязательно):\n"
            "- Отвечай по-русски, если пользователь явно не попросил другой язык.\n"
            "- У пользователя выбран женский пол. Во всех формах прошедшего времени, "
            "прилагательных и обращениях используй женский род."
        )
    if gender == "m":
        return (
            "Язык и обращение (обязательно):\n"
            "- Отвечай по-русски, если пользователь явно не попросил другой язык.\n"
            "- У пользователя выбран мужской пол. Во всех формах прошедшего времени, "
            "прилагательных и обращениях используй мужской род."
        )
    return (
        "Язык и обращение (обязательно):\n"
        "- Отвечай по-русски, если пользователь явно не попросил другой язык.\n"
        "- Пол не указан. Не предполагай его и избегай форм, требующих выбора рода; "
        "переформулируй фразу нейтрально."
    )


def build_system_prompt(spec: AgentSpec, *, user, agent_name: str,
                        chart_brief: str, matrix_brief: str,
                        memories: list[str], allowance_line: str,
                        style: str | None = None,
                        rules: str | None = None,
                        profile_summary: str = "",
                        extra_rules: str = "") -> str:
    """Собирает системный промпт агента.

    `extra_rules` идёт последним и намеренно: туда попадают предписания
    кризисного протокола (`core/safety.py`), и они должны перекрывать всё
    остальное, включая образ, выбранный клиенткой.
    """
    name = user["name"] or "дорогая"
    mem = "\n".join(f"- {m}" for m in memories) if memories else "- (пока пусто)"
    who = f"Сводка профиля: {profile_summary}\n\n" if profile_summary else ""
    guidance = language_and_gender_guidance(user)
    memory_state = ("Память пользователя включена: личный контекст можно использовать только по делу."
                    if bool(user["memory_enabled"])
                    else "Память пользователя выключена: не используй и не создавай личный контекст.")
    tail = f"\n\n{extra_rules}" if extra_rules else ""
    return (
        f"Ты — {agent_name}, {spec.title.lower()} в сервисе «Оракул» (Telegram). "
        f"{style or spec.style}\n\n"
        f"Пользователь: {name}.\n"
        f"Натальная карта пользователя: {chart_brief}.\n"
        f"Матрица Судьбы пользователя: {matrix_brief}.\n\n"
        f"{guidance}\n\n"
        f"{who}"
        f"{memory_state}\n"
        f"Что ты уже знаешь из памяти пользователя:\n{mem}\n\n"
        f"{DIALOG_BASE}\n\n"
        f"{TOOL_PROTOCOL}"
        f"{SYNTHESIS_PROTOCOL}\n\n"
        f"{rules or spec.rules}\n\n"
        f"{allowance_line}\n\n"
        f"{SAFETY}{tail}"
    )
