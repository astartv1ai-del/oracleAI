def _r(n: int) -> int:
    """Свести число к аркану 1..22."""
    while n > 22:
        n = sum(int(c) for c in str(n))
    return n if n > 0 else 22


def compute_matrix(birth_date: str) -> dict:
    d = datetime.strptime(birth_date, "%Y-%m-%d")
    a = _r(d.day)                       # личный аркан (характер)
    b = _r(d.month)                     # духовный аркан
    c = _r(sum(int(x) for x in str(d.year)))  # родовой аркан
    dd = _r(a + b + c)                  # аркан судьбы (миссия)
    e = _r(a + b + c + dd)              # центр матрицы (зона комфорта)
    love = _r(dd + e)                   # линия отношений
    money = _r(c + dd)                  # линия финансов

    def item(n, title):
        name, meaning = ARCANA[n]
        return {"n": n, "arcana": name, "meaning": meaning, "title": title}

    return {
        "personal": item(a, "Личный аркан"),
        "spirit": item(b, "Духовный аркан"),
        "family": item(c, "Родовой аркан"),
        "destiny": item(dd, "Аркан судьбы"),
        "center": item(e, "Центр матрицы"),
        "love": item(love, "Линия любви"),
        "money": item(money, "Линия денег"),
    }


def matrix_brief(m: dict) -> str:
    return "; ".join(f"{v['title']}: {v['n']} {v['arcana']}" for v in m.values())
